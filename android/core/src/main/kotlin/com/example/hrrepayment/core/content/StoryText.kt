package com.example.hrrepayment.core.content

/** Stable story mapping; reading text never changes the saved game. */
object StoryText {
    fun eventTitle(id: String): String = when (id) {
        "chapter2_success" -> "工作评价"
        "manager_handover" -> "人事变动"
        "overseas_offer", "overseas_missed" -> "外派结果"
        "winter_cold" -> "身体状况"
        else -> "通知"
    }

    fun eventBody(id: String): String = when (id) {
        "chapter2_success" -> "我收到录用确认，这次推送通过了。林主管给我的工作评价多了一句肯定。\n\n我把通知又看了一遍。履历上的学校是假的，这次做成的事是真的。"
        "manager_handover" -> "我收到人事通知：林维离职，周宁接任招聘负责人。\n\n工资没有变。过去那些‘做得不错’，却像是跟着林主管一起离开了。我得重新让接收结果的人相信我。"
        "overseas_offer" -> "我收到周负责人的外派通知：工作考核、英语和部门推荐都已通过，我进入了派驻名单。\n\n我先打开的却是欠款页面。"
        "overseas_missed" -> "我打开周负责人转来的派驻名单，没有找到自己。\n\n名额给了别人。我关掉通知，今天的两份简历还在等着我。"
        "winter_cold" -> "我感冒了，浑身发沉。平时扫一眼就能看完的几行字，今天总要再读一遍。\n\n我原本想照常把今天的工作做完。"
        else -> ""
    }

    fun endingTitle(id: String?): String = when (id) {
        "overseas_repaid" -> "远赴重洋·人生逆袭"
        "debt_free_restart" -> "一身轻松·苦涩重启"
        "overseas_indebted" -> "凭空消失·逍遥法外"
        "bankruptcy" -> "深渊滚雪球·赌徒末路"
        "indebted_layoff" -> "时代一粒灰·困顿底层"
        "health_death" -> "时空交错·时代尘埃"
        "low_dopamine" -> "烂命一条"
        "exposed" -> "露出马脚"
        else -> "游戏结束"
    }

    fun endingBody(id: String?, reason: String?): String = when (id) {
        "overseas_repaid" -> "欠款是零。我又核对了一次，不用再从下个月的工资里替过去划走一笔钱了。\n\n当初让我进门的是一份假学历。现在，审核过的材料、学过的英语和做过的工作，终于给了我一点实在的底气。\n\n后来，我按通知完成了项目交接和派驻准备。年底行程敲定，年初出发。出发前，我把结清的账单又看了一遍，才关掉那个页面。\n\n入职档案里的那一栏仍然不是真的。我不知道它什么时候会再被打开，但至少这一次，我有了不用借钱也能开始的生活。"
        "debt_free_restart" -> if (reason == "trust_negative" || reason == "exposed_debt_zero") {
            "我收到入职材料复核结论。那份境外学历没有通过核验，公司通知我终止任职。\n\n我每天都在判断别人的材料，这一次轮到了自己。做过的工作没有消失，但它们不能替那张假的证明作证。\n\n我又看了一眼账单。欠款已经结清，这段日子并不是什么都没留下。\n\n我新建了一份简历，删掉那所学校。从自己的真实经历开始写，比我想象中慢得多。下一次能不能被选中，我不知道。"
        } else {
            "我核对完最后一张账单。欠款是零，明年的工资终于可以留给明年的生活。\n\n我开始想着，下一份自己的简历，要不要把那所从没去过的学校删掉。\n\n后来，疫情的消息占满了屏幕。\n\n那一天来了，一切的计划消失。\n\n我收到裁员谈判的通知。高管招聘、内部争执，还有那些要我把不合规材料写成‘没问题’的脏活，一件件又被翻出来。我没有照做，也没能在这些争执里保住位置。离职通知最终还是到了。\n\n我重新打开自己的简历。这一次，我删掉了那所学校，留下真正做过的工作。面试还没有着落，至少欠款那一栏不用再跟着我了。"
        }
        "overseas_indebted" -> "欠款还在。外派通知没有问起它，我也没有主动提。\n\n后来，我借着派驻安排离开，停用了国内常用的联系方式。工作往来留在公司的系统里，其余消息被我留在了另一个号码上。\n\n那条路并不干净，至少让我暂时不用每天看见催款。我把这种安静叫作重新开始。\n\n可我没有收到任何一张结清证明。连同那份假学历，我只是把旧事放到了暂时没人问起的地方。"
        "bankruptcy" -> if (reason == "cash_exhausted") {
            "我反复刷新余额，数字没有变。可用的钱已经耗尽，欠款却还在。\n\n我一直拿下一次到账安排眼前的日子，好像只要能算出下一步，就能继续撑下去。\n\n现在，下一步用的钱也没了。今天的账单不会因为我还在等一笔钱，就算已经还过。\n\n屏幕上还列着未来的日期。我停在了这里。"
        } else {
            "年底的利息记进了账单。我核对过还款记录，欠款仍然越过了六十万。\n\n那是我刚开始时欠下的数额。我曾经以为，只要工资一笔笔到账，这个数字总会越来越小。\n\n我把账单往前翻，想找出是哪一步失了算。利息已经计入，翻回任何一页都改不了这一期的结果。\n\n我又回到了那个起点之外。"
        }
        "indebted_layoff" -> "最后一年的账结完了，欠款还没有清。我把明年的工资排进计划，想着再熬一阵，也许就能把这一段补上。\n\n后来，疫情的消息占满了屏幕。\n\n那一天来了，一切的计划消失。\n\n裁员通知到了。我先看日期，再算工资还能算到哪一天。计划里最确定的一行，也空了。\n\n我开始往外投简历。以前，我在两个人里挑一个；现在，我等着别人从一堆人里挑到我。\n\n每次提示亮起，我都先以为是面试消息。有时只是账单。欠款还在，我也还得继续找工作。"
        "health_death" -> if (reason == "cold_health_low") {
            "我想先看完第一份简历，手指停在半页上。字挤在一起，我又从上一行开始读。\n\n我把手机放低了一点，想着缓一会儿再继续。今天的日期还亮着，工作还没有做完。\n\n后面的字，我没有读完。"
        } else {
            "我核对完年底的账，想把手机放下。这个动作慢得出奇。\n\n我总把休息排在工作和账单后面，觉得等这些事处理完，时间就会空出来。\n\n屏幕上的日期停在十二月的最后一天。我想再看清一点，眼前的字却越来越远。"
        }
        "low_dopamine" -> "很久了，我每天都把相同的几件事做完，却想不出做完以后还想要什么。\n\n我把这样的自己骂作‘烂命一条’。骂完并没有好一点。我连解释自己哪里难受，都觉得费力。\n\n那晚，我起了结束自己生命的念头。我没有把这件事告诉任何人，屏幕上留下的仍是那些工作提醒。\n\n最后一条提示亮起。我没有再点开。"
        "exposed" -> "我收到入职材料复核结论。那份境外学历没有通过核验，公司通知我终止任职。\n\n这回没有两份材料可以比较，也没有另一个名字可以推过去。被要求解释的是我自己的那一栏。\n\n我准备过很多次说法。结论发来以后，那些话一句也用不上。\n\n欠款还在，下一份工资却不能再照着原来的数往下算。我关掉公司的通知，重新打开了自己的简历。"
        else -> "我停在了这里。"
    }
}
